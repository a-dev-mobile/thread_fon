extension DoubleExtension on double {
  /// Преобразует число в строку с заданным количеством знаков после запятой.
  /// Убирает лишние нули в конце. Если после запятой только нули, убирает и точку.
  ///
  /// [decimalPlaces] — количество знаков после запятой.
  /// Возвращает строковое представление числа с указанной точностью.
  String toPrecisionString(int decimalPlaces) {
    // Проверяем, что количество знаков не отрицательное
    if (decimalPlaces < 0) {
      throw ArgumentError(
        'Количество знаков после запятой не может быть отрицательным',
      );
    }

    // Преобразуем число в строку с фиксированной точностью
    String str = toStringAsFixed(decimalPlaces);

    // Удаляем лишние нули и, если необходимо, точку
    // Регулярное выражение:
    // \.? - опциональная точка
    // 0+$ - последовательность из одних нулей до конца строки
    str = str.replaceFirst(RegExp(r'\.?0+$'), '');

    return str;
  }
}
